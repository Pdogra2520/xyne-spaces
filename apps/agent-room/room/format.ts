import { getPattern } from './patterns';
import type { DecisionRecord, Intervention, RoomConfig, Turn } from './types';

const FENCE = '`'.repeat(3);

const STANCE_ICON: Record<string, string> = {
  for: '🟢 for', against: '🔴 against', conditional: '🟡 conditional', unknown: '⚪ unclear',
};

/** First message of the room thread. Human summary + machine-readable config block. */
export function formatConfigMessage(cfg: RoomConfig): string {
  const pattern = getPattern(cfg.patternId);
  const seats = cfg.seats
    .map((s) => `- **${s.label}** · ${s.patternRole} · ${s.kind === 'agent' ? `Claw agent \`${s.agentSlug}\`` : 'persona'}`)
    .join('\n');
  return `🏛️ **Agent Room: ${cfg.title}**

**Question:** ${cfg.question}
**Pattern:** ${pattern.name} · **Outcome:** ${cfg.outcome}
**Seats:**
${seats}

_Every turn below is written by an AI agent and posted by the Agent Room app on behalf of the room owner. Agents only debate; they do not take actions._

${FENCE}agent-room-config
${JSON.stringify(cfg, null, 2)}
${FENCE}`;
}

export function formatRoundHeader(round: number, total: number, name: string): string {
  return `── **Round ${round}/${total}: ${name}** ──`;
}

export function formatTurnMessage(t: Turn): string {
  const header = `**[Agent Room · ${t.id} · ${t.seatLabel} · ${t.patternRole}]** ${STANCE_ICON[t.stance] ?? ''}${t.changedMind ? ' · ↺ changed mind' : ''}`;
  if (t.status !== 'ok') return `${header}\n_No response (${t.status}): ${t.text}_`;
  return `${header}\n\n${t.text.trim()}`;
}

export function formatIntervention(i: Intervention, owner: string): string {
  return `📌 **Fact added by ${owner} (after round ${i.afterRound}):** ${i.text}`;
}

function list(items: string[]): string {
  return items.length ? items.map((x) => `- ${x}`).join('\n') : '- None recorded';
}

export function formatDecisionMarkdown(cfg: RoomConfig, d: DecisionRecord, turns: Turn[]): string {
  const stanceTable = cfg.seats
    .map((s) => {
      const mine = turns.filter((t) => t.seatId === s.id && t.status === 'ok');
      const path = mine.map((t) => t.stance).join(' → ') || 'no turns';
      return `| ${s.label} | ${s.patternRole} | ${path} |`;
    })
    .join('\n');
  return `# Decision: ${cfg.title}

**Question:** ${cfg.question}

## Decision
**${d.decision}**

Confidence: **${d.confidence}**

## Rationale
${d.rationale || '_Not given._'}

## Strongest arguments for
${list(d.strongestFor)}

## Strongest arguments against
${list(d.strongestAgainst)}

## Dissent
${list(d.dissent)}

## Open risks
${list(d.openRisks)}

## Follow-ups
${list(d.followUps)}

## How positions moved
| Seat | Role | Stance by round |
|---|---|---|
${stanceTable}

## Evidence
Cited turns: ${d.citedTurns.join(', ')}

_Generated by Agent Room · pattern ${getPattern(cfg.patternId).name} · ${turns.length} turns. This is an AI recommendation; a person owns the final call._`;
}

export function formatDecisionMessage(d: DecisionRecord, canvasUrl: string | null): string {
  const link = canvasUrl ? `\n\n📄 Full decision record: ${canvasUrl}` : '';
  return `⚖️ **Decision:** ${d.decision}\n**Confidence:** ${d.confidence}\n\n${d.rationale}${link}`;
}
